      <h3 class="about-history__title">経歴</h3>
      <p class="about-history__text">
        Daisy Music Academy代表。<br>
        武蔵野音楽大学大学院ピアノ専攻修了。<br>
        在学中より国内外で研鑽を積み、チェコ音楽コンクール第1位、DAAD奨学生としてドイツ・フランス各地の音楽アカデミーに参加し、選抜コンサートにも多数出演。<br>
        国内外での演奏経験を経て、教育の道へ進む。<br>
        大学院修了後、武蔵野音楽大学附属江古田音楽教室のソルフェージュ講師に抜擢。<br>
        以来14年間にわたり、延べ2万人以上の子どもたちのソルフェージュ教育に携わる。<br>
        教育の現場で「音楽は技術だけではなく、心を育てる力である」ことを実感し、“感じる心”と“考える力”を両輪とする独自の指導観を築く。<br>
        2023年には、同大学講師研究会にて発表者に選抜され、「読譜・音感指導における多角的アプローチと実践〜音楽表現に結びつけるためのソルフェージュ〜」をテーマに登壇。<br>
        長年教育に携わる講師陣の前で研究内容を発表し、多くの共感と関心を集めた。<br>
        指導経験をもとに、歌って楽譜が読めるようになるオリジナルメソッド「うたハノン®」を開発。全国の音楽指導者向け指導法講座を主宰し、<br>
        これまでに延べ1,000名以上が受講。「生徒が変わった！」という声が全国から届いている。<br>
        現在は、指導法講座・オンラインスクール・音楽教室の三軸で活動。<br>
        子どもから指導者まで、音楽の根っこを育てる教育を実践している。<br>
        2025年12月には、ヤマハミュージックエンタテインメントホールディングスより著書『生徒が変わる！ 新しいソルフェージュ指導の教科書』を出版予定。<br>
        音楽を“技術”としてだけでなく、「感じる心」と「考える力」を育てる学びとして伝え続けている。
      </p>
